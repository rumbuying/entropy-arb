let _lang = localStorage.getItem("lang") ||
  ((navigator.language || "en").toLowerCase().startsWith("zh") ? "zh" : "en");

export function getLang() { return _lang; }

export function setLang(lang) {
  _lang = lang === "zh" ? "zh" : "en";
  localStorage.setItem("lang", _lang);
  document.documentElement.lang = _lang;
}

export function t(key, params) {
  let s = (STRINGS[_lang] && STRINGS[_lang][key]) ||
          STRINGS.en[key] || key;
  if (params) s = s.replace(/\{(\w+)\}/g, (_, k) =>
    params[k] !== undefined ? params[k] : `{${k}}`);
  return s;
}

// Re-translate all elements carrying data-i18n (params not supported there).
export function applyStatic(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  root.querySelectorAll("[data-i18n-ph]").forEach(el => {
    el.placeholder = t(el.getAttribute("data-i18n-ph"));
  });
}
