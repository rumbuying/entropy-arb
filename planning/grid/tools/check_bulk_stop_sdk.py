"""Offline stop signing check against public official Rust oracle vectors.

Run in the isolated Linux SDK environment. The oracle is generated by the
pinned official bulk-client Action.hash(), not by this probe. The ephemeral
unfunded key was generated for this exact local-only run, never submitted.
"""
import argparse
import copy
import hashlib
import json
from pathlib import Path
import struct
import sys

sys.path.insert(0,str(Path(__file__).resolve().parents[3]))

from entropy_arb.grid import models
from entropy_arb.grid.adapters.base import AdapterError
from entropy_arb.grid.adapters.bulk_wire import BulkKeychain, base58
from entropy_arb.grid.adapters.bulk_identity import (SOURCE_REVISION, STOP_HASH_SOURCE_REVISION,
    STOP_HASH_SCHEMA, BulkSdkStopIdentity)


class VectorOracle:
    def __init__(self,rows,revision=SOURCE_REVISION):
        self.rows={models.sha256_hex([r['action'],r['account'],r['nonce']]):r for r in rows}
        self.revision=revision

    def calculate(self,*,action,owner,nonce):
        try:row=self.rows[models.sha256_hex([action,owner,nonce])]
        except KeyError:raise AdapterError('BULK_NATIVE_VECTOR_UNBOUND') from None
        if row['source_revision']!=self.revision:raise AdapterError('BULK_NATIVE_VECTOR_SOURCE_INVALID')
        return row


def probe(vectors,oracle,secret,*,portable=False,hash_oracle=None):
    import bulk_keychain
    if hash_oracle is None:raise AdapterError('BULK_NATIVE_STOP_HASH_ORACLE_REQUIRED')
    provider=VectorOracle(oracle['rows']);results=[];identities={}
    hash_provider=VectorOracle(hash_oracle['rows'],STOP_HASH_SOURCE_REVISION)
    class CorrectedOracle:
        def calculate(self,**args):
            signing=provider.calculate(**args);root=hash_provider.calculate(**args)
            assert signing['canonical_action_hex']==root['canonical_action_hex']+'0000'
            return {k:v for k,v in signing.items() if k!='action'}|dict(order_id=root['order_id'],
                order_hash_source_revision=STOP_HASH_SOURCE_REVISION,order_hash_schema=STOP_HASH_SCHEMA)
    for row in vectors['rows']:
        implementation=BulkSdkStopIdentity(network=row['network']) if portable else CorrectedOracle()
        protocol=BulkKeychain(network=row['network'],owner=row['owner'],secret=secret,native_identity=implementation)
        symbol=row.get('symbol','ETH-USD')
        prepared=protocol.prepare_stop(symbol,row['size'],row['trigger'],row['nonce'])
        # Exercise the same action dispatch used by the durable probe journal,
        # rather than certifying only the direct prepare_stop helper.
        assert protocol.prepare(dict(type='stop',symbol=symbol,size=row['size'],
            trigger_price=row['trigger'],iso=False),row['nonce'])==prepared
        assert bytes(prepared['message_bytes']).hex()==row['message_hex']
        expected=CorrectedOracle().calculate(action=prepared['actions'][0],owner=row['owner'],nonce=row['nonce'])
        canonical=bytes.fromhex(expected['canonical_action_hex'])
        assert implementation.calculate(action=prepared['actions'][0],owner=row['owner'],nonce=row['nonce'])==expected
        offset=12+len(symbol)
        assert struct.unpack_from('<IQ',canonical)==(5,len(symbol))
        assert canonical[12:offset]==symbol.encode() and canonical[offset]==0
        from decimal import Decimal
        size,trigger=struct.unpack_from('<QQ',canonical,offset+1)
        assert size==int(Decimal(row['size'])*10**8) and trigger==int(Decimal(row['trigger'])*10**8)
        assert canonical[offset+17:]==b'\0'*4 and len(canonical)==offset+21
        signed=protocol.sign(prepared)
        assert signed['order_id']==expected['order_id']
        assert bulk_keychain.finalize_transaction(prepared,signed['signature'])['signature']==signed['signature']
        for field in ('id','direction','message'):
            changed=copy.deepcopy(prepared)
            if field=='id':changed['order_id']=row['owner']
            elif field=='direction':changed['actions'][0]['st']['d']=True
            else:
                changed['message_bytes']=bytes(changed['message_bytes'])[:-1]+b'\x03'
            try:protocol.sign(changed)
            except AdapterError:pass
            else:raise AssertionError('changed stop preparation was accepted')
        identity_key=(symbol,row['nonce'],row['size'],row['trigger'])
        if identity_key in identities:assert identities[identity_key]==signed['order_id']
        identities[identity_key]=signed['order_id']
        results.append(dict(network=row['network'],symbol=symbol,nonce=str(row['nonce']),size=row['size'],trigger=row['trigger'],
            order_id=signed['order_id'],canonical_matches_official_rust=True,signed_units_exact=True,
            order_id_matches_official_legacy_rust=True,signature_verified=True,tampering_rejected=True))
    return dict(cases=results,oracle_revision=SOURCE_REVISION,oracle_binary_sha256=oracle['binary_sha256'],
        order_hash_oracle_revision=STOP_HASH_SOURCE_REVISION,order_hash_oracle_binary_sha256=hash_oracle['binary_sha256'],
        sdk_version='0.1.30',financial_transmissions=0,live_qualified=False,
        production_helper_installed=False,ephemeral_unfunded_key=True,
        identity_backend='sdk-v4-signing-six-field-stop-hash-v2' if portable else 'dual-official-rust-vector-oracle',
        identity_source_sha256=hashlib.sha256(Path(sys.modules[BulkSdkStopIdentity.__module__].__file__).read_bytes()).hexdigest(),
        source_sha256=hashlib.sha256(Path(sys.modules[BulkKeychain.__module__].__file__).read_bytes()).hexdigest())


if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--vectors',required=True);ap.add_argument('--oracle',required=True)
    ap.add_argument('--hash-oracle',required=True)
    ap.add_argument('--ephemeral-key-file',required=True)
    ap.add_argument('--portable',action='store_true')
    args=ap.parse_args()
    secret=Path(args.ephemeral_key_file).read_text().strip()
    print(json.dumps(probe(json.loads(Path(args.vectors).read_text()),json.loads(Path(args.oracle).read_text()),secret,
        portable=args.portable,hash_oracle=json.loads(Path(args.hash_oracle).read_text())),indent=2))
